export const categories = ['ولد', 'بنت', 'بلد', 'حيوان', 'جماد'] as const;
export type Category = typeof categories[number];

export const availableLetters = Object.keys(arabicWords);

export function getRandomLetters(count: number): string[] {
  const shuffled = [...availableLetters].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function validateAnswer(letter: string, category: Category, answer: string): boolean {
  const trimmedAnswer = answer.trim();
  if (!trimmedAnswer) return false;
  
  const letterData = arabicWords[letter];
  if (!letterData) return false;
  
  const validWords = letterData[category] || [];
  return validWords.some(word => 
    word.toLowerCase() === trimmedAnswer.toLowerCase() ||
    word.includes(trimmedAnswer) ||
    trimmedAnswer.includes(word)
  );
}
