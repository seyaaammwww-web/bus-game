// 1. CLEANUP MISTAKE
function cleanup() {
    console.log("🧹 Cleaning up 'Misr' from letter 'Alef'...");
    const db = JSON.parse(fs.readFileSync(dbPath, 'utf-8'));
    if (db['أ'] && db['أ']['بلد']) {
        db['أ']['بلد'] = db['أ']['بلد'].filter((w: string) => w !== 'مصر');
        fs.writeFileSync(dbPath, JSON.stringify(db, null, 2));
        console.log("✅ Removed 'مصر' from 'أ'.");
    }
}

