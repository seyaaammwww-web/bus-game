async function runExpansion() {
    cleanup();
    console.log("🚀 Starting Massive Egyptian Vocabulary Injection...");
    let addedCount = 0;

    for (const [letter, cats] of Object.entries(expansion)) {
        for (const [catName, words] of Object.entries(cats)) {
            // Map 'نبات' to 'جماد' if present
            const targetCategory = catName === 'نبات' ? 'جماد' : catName;

            for (const word of words) {
                const added = service.addWord(letter, targetCategory, word);
                if (added) addedCount++;
            }
        }
    }

    console.log(`✅ Injection Complete. Added ${addedCount} everyday words.`);
}

runExpansion();
