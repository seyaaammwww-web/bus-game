async function expandDB() {
    console.log("🚀 Starting HLEE Expansion Protocol...");

    // We can't easily perform "addWord" because the method works one by one and reads/writes file.
    // For bulk, let's load, modify, write.

    const service = WildcardService.getInstance();

    let addedCount = 0;

    for (const [letter, categories] of Object.entries(expansionPack)) {
        for (const [category, words] of Object.entries(categories)) {
            for (const word of words) {
                // Use the service's addWord which handles normalization and duplication checks
                // Note: efficient bulk add would be better, but this ensures consistency
                const success = service.addWord(letter, category, word);
                if (success) {
                    process.stdout.write(`+`); // Progress indicator
                    addedCount++;
                } else {
                    process.stdout.write(`.`); // Skipped
                }
            }
        }
    }

    console.log(`\n\n✅ Expansion Complete! Added ${addedCount} new highly-relevant words.`);
}

expandDB();
