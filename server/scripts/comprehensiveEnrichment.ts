async function enrichDatabase() {
    console.log('🚀 Starting Database Enrichment...\n');

    const dbPath = path.join(process.cwd(), 'server/data/clean_wildcardDatabase.json');

    if (!fs.existsSync(dbPath)) {
        console.error('❌ Database file not found:', dbPath);
        return;
    }

    // Load existing database
    const database: WildcardDatabase = JSON.parse(fs.readFileSync(dbPath, 'utf-8'));
    console.log('✅ Loaded existing database\n');

    let totalAdded = 0;
    let totalSkipped = 0;

    // Process each category
    for (const [category, letterData] of Object.entries(ENRICHMENT_DATA)) {
        console.log(`📝 Processing category: ${category}`);

        for (const [letter, words] of Object.entries(letterData)) {
            // Initialize if needed
            if (!database[letter]) {
                database[letter] = {};
            }
            if (!database[letter][category]) {
                database[letter][category] = [];
            }

            // Add words
            for (const word of words) {
                const exists = database[letter][category].some(
                    existing => normalizeArabic(existing) === normalizeArabic(word)
                );

                if (!exists) {
                    database[letter][category].push(word);
                    totalAdded++;
                } else {
                    totalSkipped++;
                }
            }

            // Sort alphabetically
            database[letter][category].sort();
        }
    }

    // Save updated database
    fs.writeFileSync(dbPath, JSON.stringify(database, null, 2), 'utf-8');

    console.log('\n✅ Database Enrichment Complete!');
    console.log(`📊 Added: ${totalAdded} words`);
    console.log(`⏭️  Skipped (duplicates): ${totalSkipped} words`);
    console.log(`💾 Saved to: ${dbPath}`);
}

function normalizeArabic(text: string): string {
    return text
        .trim()
        .toLowerCase()
        .replace(/[أإآٱ]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/ى/g, 'ي')
        .replace(/[ءؤئ]/g, 'ا')
        .replace(/[\u064B-\u065F\u0670]/g, '');
}

// Run enrichment
enrichDatabase().catch(console.error);
